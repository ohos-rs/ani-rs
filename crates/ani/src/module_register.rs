/// Execute init callbacks that should run before native binding registration.
#[doc(hidden)]
pub unsafe fn execute_before_bindings_inits(env: *mut sys::ani_env) -> sys::ani_status {
    let callbacks = INIT_BEFORE_BINDINGS_CALLBACKS
        .read()
        .expect("Failed to acquire read lock for INIT_BEFORE_BINDINGS_CALLBACKS");

    for entry in callbacks.iter() {
        // SAFETY: The callback is a function pointer registered via #[ani(init)] macro
        let status = unsafe { (entry.callback)(env) };
        if status != sys::ani_status_ANI_OK {
            eprintln!("Failed to run before_bindings init: {}", entry.name);
            return status;
        }
    }

    sys::ani_status_ANI_OK
}

/// Execute all registered callbacks
///
/// Called by `ANI_Constructor` to bind all native functions
#[doc(hidden)]
pub unsafe fn execute_registrations(env: *mut sys::ani_env) -> sys::ani_status {
    let callbacks = MODULE_REGISTER_CALLBACKS
        .read()
        .expect("Failed to acquire read lock for MODULE_REGISTER_CALLBACKS");
    let debug = std::env::var("ANI_DEBUG_REGISTER").ok().as_deref() == Some("1");
    PENDING_BINDINGS
        .write()
        .expect("Failed to acquire write lock for PENDING_BINDINGS")
        .clear();

    if debug {
        eprintln!("[ani] execute_registrations count={}", callbacks.len());
    }

    for entry in callbacks.iter() {
        if debug {
            eprintln!("[ani] register begin: {}", entry.name);
        }
        // SAFETY: The callback is a function pointer registered via #[ani] macro
        let status = unsafe { (entry.callback)(env) };
        if debug {
            eprintln!("[ani] register end: {} status={}", entry.name, status);
        }
        if status != sys::ani_status_ANI_OK {
            eprintln!(
                "Failed to register function: {} (status={})",
                entry.name, status
            );
            return status;
        }
    }

    let pending = PENDING_BINDINGS
        .read()
        .expect("Failed to acquire read lock for PENDING_BINDINGS");

    let mut grouped: BTreeMap<(BindingTargetKind, &'static str), Vec<sys::ani_native_function>> =
        BTreeMap::new();
    for entry in pending.iter() {
        grouped
            .entry((entry.target_kind, entry.descriptor))
            .or_default()
            .push(sys::ani_native_function {
                name: entry.name as *const c_char,
                signature: entry.signature as *const c_char,
                pointer: entry.pointer as *const c_void,
            });
    }
    drop(pending);

    if grouped.is_empty() {
        if debug {
            eprintln!("[ani] no pending bindings");
        }
        return sys::ani_status_ANI_OK;
    }

    let api = unsafe {
        // SAFETY: `env` comes from ANI entrypoints and is expected to be a valid
        // pointer to `ani_env`, whose first field points to API table.
        &*(*env)
    };
    for ((target_kind, descriptor), functions) in grouped {
        if debug {
            eprintln!(
                "[ani] bind target={target_kind:?} descriptor={descriptor} count={}",
                functions.len()
            );
            for (idx, f) in functions.iter().enumerate() {
                let name = if f.name.is_null() {
                    "<null>"
                } else {
                    // SAFETY: debug-only diagnostics for static C string literals.
                    unsafe { CStr::from_ptr(f.name) }
                        .to_str()
                        .unwrap_or("<invalid>")
                };
                let sig = if f.signature.is_null() {
                    "<null>"
                } else {
                    // SAFETY: debug-only diagnostics for static C string literals.
                    unsafe { CStr::from_ptr(f.signature) }
                        .to_str()
                        .unwrap_or("<invalid>")
                };
                eprintln!(
                    "[ani]   fn[{idx}] name={name} sig={sig} ptr={:p}",
                    f.pointer
                );
            }
        }

        let status = match target_kind {
            BindingTargetKind::ClassInstance => {
                let (status, cls) =
                    unsafe { find_class_with_fallback(api, env, descriptor, debug) };
                if status != sys::ani_status_ANI_OK {
                    status
                } else if cls.is_null() {
                    sys::ani_status_ANI_NOT_FOUND
                } else {
                    unsafe {
                        (api.Class_BindNativeMethods.unwrap())(
                            env,
                            cls,
                            functions.as_ptr(),
                            functions.len(),
                        )
                    }
                }
            }
            BindingTargetKind::ClassStatic => {
                let (status, cls) =
                    unsafe { find_class_with_fallback(api, env, descriptor, debug) };
                if status != sys::ani_status_ANI_OK {
                    status
                } else if cls.is_null() {
                    sys::ani_status_ANI_NOT_FOUND
                } else {
                    unsafe {
                        (api.Class_BindStaticNativeMethods.unwrap())(
                            env,
                            cls,
                            functions.as_ptr(),
                            functions.len(),
                        )
                    }
                }
            }
            BindingTargetKind::Namespace => {
                let (status, ns) =
                    unsafe { find_namespace_with_fallback(api, env, descriptor, debug) };
                if status != sys::ani_status_ANI_OK {
                    status
                } else if ns.is_null() {
                    sys::ani_status_ANI_NOT_FOUND
                } else {
                    unsafe {
                        (api.Namespace_BindNativeFunctions.unwrap())(
                            env,
                            ns,
                            functions.as_ptr(),
                            functions.len(),
                        )
                    }
                }
            }
            BindingTargetKind::Module => {
                if descriptor.is_empty() {
                    sys::ani_status_ANI_INVALID_ARGS
                } else {
                    let (status, module) =
                        unsafe { find_module_with_fallback(api, env, descriptor, debug) };
                    if status != sys::ani_status_ANI_OK {
                        status
                    } else if module.is_null() {
                        sys::ani_status_ANI_NOT_FOUND
                    } else {
                        if debug {
                            for (idx, f) in functions.iter().enumerate() {
                                let mut found: sys::ani_function = core::ptr::null_mut();
                                let check_status = unsafe {
                                    (api.Module_FindFunction.unwrap())(
                                        env,
                                        module,
                                        f.name,
                                        f.signature,
                                        &mut found,
                                    )
                                };
                                eprintln!(
                                    "[ani]   precheck module fn[{idx}] find_status={check_status} ptr={found:p}"
                                );
                            }
                        }
                        unsafe {
                            (api.Module_BindNativeFunctions.unwrap())(
                                env,
                                module,
                                functions.as_ptr(),
                                functions.len(),
                            )
                        }
                    }
                }
            }
        };

        if debug {
            eprintln!("[ani] bind done target={target_kind:?} status={status}");
        }

        if status != sys::ani_status_ANI_OK {
            return status;
        }
    }

    sys::ani_status_ANI_OK
}

/// Execute init callbacks that should run after native binding registration.
#[doc(hidden)]
pub unsafe fn execute_after_bindings_inits(env: *mut sys::ani_env) -> sys::ani_status {
    let callbacks = INIT_AFTER_BINDINGS_CALLBACKS
        .read()
        .expect("Failed to acquire read lock for INIT_AFTER_BINDINGS_CALLBACKS");

    for entry in callbacks.iter() {
        // SAFETY: The callback is a function pointer registered via #[ani(init)] macro
        let status = unsafe { (entry.callback)(env) };
        if status != sys::ani_status_ANI_OK {
            eprintln!("Failed to run after_bindings init: {}", entry.name);
            return status;
        }
    }

    sys::ani_status_ANI_OK
}

/// Get the number of registered callbacks (for debugging)
#[doc(hidden)]
pub fn registered_count() -> usize {
    MODULE_REGISTER_CALLBACKS
        .read()
        .expect("Failed to acquire read lock for MODULE_REGISTER_CALLBACKS")
        .len()
}

/// Clear all registered callbacks (for testing)
#[cfg(test)]
#[doc(hidden)]
pub fn clear_registrations() {
    MODULE_REGISTER_CALLBACKS
        .write()
        .expect("Failed to acquire write lock for MODULE_REGISTER_CALLBACKS")
        .clear();
    INIT_BEFORE_BINDINGS_CALLBACKS
        .write()
        .expect("Failed to acquire write lock for INIT_BEFORE_BINDINGS_CALLBACKS")
        .clear();
    INIT_AFTER_BINDINGS_CALLBACKS
        .write()
        .expect("Failed to acquire write lock for INIT_AFTER_BINDINGS_CALLBACKS")
        .clear();
    PENDING_BINDINGS
        .write()
        .expect("Failed to acquire write lock for PENDING_BINDINGS")
        .clear();
}

#[cfg(test)]
mod tests {
    use super::*;
    use core::ptr;
    use std::sync::Mutex;

    static TEST_LOCK: Mutex<()> = Mutex::new(());

    #[test]
    fn descriptor_candidates_non_builtin_has_defmodule_fallback() {
        let candidates = descriptor_candidates("a.b.C");
        assert_eq!(
            candidates,
            vec!["a.b.C".to_string(), "@defModule.a.b.C".to_string()]
        );
    }

    #[test]
    fn descriptor_candidates_builtin_has_no_defmodule_fallback() {
        let candidates = descriptor_candidates("std.core.String");
        assert_eq!(candidates, vec!["std.core.String".to_string()]);
    }

    #[test]
    fn queue_class_binding_sets_target_kind() {
        let _guard = TEST_LOCK.lock().expect("lock test mutex");
        clear_registrations();

        let status = queue_class_binding("demo.Test", false, "m1", ":", ptr::null());
        assert_eq!(status, sys::ani_status_ANI_OK);
        let status = queue_class_binding("demo.Test", true, "m2", ":", ptr::null());
        assert_eq!(status, sys::ani_status_ANI_OK);

        let pending = PENDING_BINDINGS.read().expect("read pending");
        assert_eq!(pending.len(), 2);
        assert_eq!(pending[0].target_kind, BindingTargetKind::ClassInstance);
        assert_eq!(pending[1].target_kind, BindingTargetKind::ClassStatic);
        assert_eq!(pending[0].descriptor, "demo.Test");
        assert_eq!(pending[1].descriptor, "demo.Test");

        drop(pending);
        clear_registrations();
    }
}
